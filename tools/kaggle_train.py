"""Train the joint model on a Kaggle GPU from this laptop.

    python tools/kaggle_train.py push [-- --epochs 30 --n-train 100000]   # send the job (private notebook, GPU)
    python tools/kaggle_train.py status                                     # queued / running / complete / error
    python tools/kaggle_train.py fetch                                      # download results to out/models/

push packs sandbox/, data/, ml/, tools/make_training_set.py and out/training/test_real.npz into one script
(the code travels inside it, base64), writes kernel-metadata.json and runs `kaggle kernels push`. The
notebook is private. On Kaggle the script unpacks the code and runs ml.train_joints; the results land in
the notebook's output. fetch downloads them and copies joint_net.npz to out/models/joint_net.npz.
Needs the kaggle CLI with a token in ~/.kaggle (never read or printed here).
"""
import argparse
import base64
import io
import json
import pathlib
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
JOB = ROOT / "out" / "kaggle" / "job"
SLUG = "skell-joint-net"
PACK = ["sandbox", "data", "ml", "tools/make_training_set.py", "out/training/test_real.npz"]

RUNNER = '''"""Skell joint model training job (generated by tools/kaggle_train.py; the code is packed below)."""
import base64, io, os, pathlib, subprocess, sys, zipfile
CODE = "{code}"
ARGS = {args!r}
src = pathlib.Path("/tmp/skell") if pathlib.Path("/kaggle").exists() else pathlib.Path("skell_job").resolve()
src.mkdir(parents=True, exist_ok=True)
zipfile.ZipFile(io.BytesIO(base64.b64decode(CODE))).extractall(src)
out = pathlib.Path("/kaggle/working") if pathlib.Path("/kaggle/working").exists() else pathlib.Path("skell_out").resolve()
cmd = [sys.executable, "-u", "-m", "ml.train_joints", "--out", str(out), "--cache", str(src / "cache"),
       "--real", str(src / "out/training/test_real.npz")] + ARGS
print(" ".join(cmd), flush=True)
sys.exit(subprocess.call(cmd, cwd=src))
'''


def kaggle(*args, capture=False):
    exe = shutil.which("kaggle") or str(pathlib.Path(sys.executable).with_name("kaggle"))
    r = subprocess.run([exe, *args], capture_output=capture, text=True)
    if r.returncode != 0:
        raise SystemExit(f"kaggle {' '.join(args)} failed" + (f": {r.stderr or r.stdout}" if capture else ""))
    return r.stdout if capture else ""


def username():
    out = kaggle("config", "view", capture=True)
    m = re.search(r"username:\s*(\S+)", out)
    if not m:
        raise SystemExit("could not read the Kaggle username from `kaggle config view`")
    return m.group(1)


def pack() -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for item in PACK:
            p = ROOT / item
            files = [p] if p.is_file() else sorted(p.rglob("*")) if p.is_dir() else []
            if not files:
                print(f"note: {item} not found, not packed")
            for f in files:
                if f.is_file() and "__pycache__" not in f.parts:
                    z.write(f, f.relative_to(ROOT).as_posix())
    return buf.getvalue()


def push(train_args, gpu=True, dry_run=False):
    JOB.mkdir(parents=True, exist_ok=True)
    code = base64.b64encode(pack()).decode("ascii")
    (JOB / "skell_train.py").write_text(RUNNER.format(code=code, args=train_args), encoding="utf-8")
    meta = {"id": f"{username()}/{SLUG}", "title": SLUG, "code_file": "skell_train.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": gpu, "enable_internet": False,
            "dataset_sources": [], "competition_sources": [], "kernel_sources": []}
    (JOB / "kernel-metadata.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    if dry_run:
        print(f"dry run: wrote {JOB} (not pushed). Try it locally: cd {JOB} && python skell_train.py")
        return
    print(f"packed {len(code) * 3 // 4 // 1024} KB of code; pushing {meta['id']} (private, GPU {gpu})")
    kaggle("kernels", "push", "-p", str(JOB))
    print(f"pushed. Check with: python tools/kaggle_train.py status   (or https://www.kaggle.com/code/{meta['id']})")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("action", choices=["push", "status", "fetch"])
    ap.add_argument("--dry-run", action="store_true", help="push: write the job files but don't send them")
    ap.add_argument("--cpu", action="store_true", help="push without a GPU")
    argv = list(sys.argv[1:] if argv is None else argv)
    extra = argv[argv.index("--") + 1:] if "--" in argv else []      # everything after -- goes to ml.train_joints
    argv = argv[:argv.index("--")] if "--" in argv else argv
    a = ap.parse_args(argv)
    if a.action == "push":
        push(extra, gpu=not a.cpu, dry_run=a.dry_run)
    elif a.action == "status":
        print(kaggle("kernels", "status", f"{username()}/{SLUG}", capture=True).strip())
    else:
        dest = ROOT / "out" / "models" / "kaggle"
        dest.mkdir(parents=True, exist_ok=True)
        kaggle("kernels", "output", f"{username()}/{SLUG}", "-p", str(dest), "--force")
        w = dest / "joint_net.npz"
        if w.is_file():
            shutil.copy2(w, ROOT / "out" / "models" / "joint_net.npz")
            print(f"copied the weights to {ROOT / 'out' / 'models' / 'joint_net.npz'}")
        rep = dest / "report.json"
        if rep.is_file():
            r = json.loads(rep.read_text(encoding="utf-8"))
            print("synthetic val:", {k: round(v, 3) for k, v in r["val"].items() if not k.startswith("per_")})
            if "real" in r:
                for k in ("plain", "with_mirror"):
                    print(f"real drawings ({k}): mean {r['real'][k]['mean_pct']:.1f}% of figure size")


if __name__ == "__main__":
    main()
